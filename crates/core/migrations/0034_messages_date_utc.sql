-- Даты писем приводим к UTC. Заголовок Date приходит в зоне отправителя, и в
-- базе рядом лежали "...+03:00" и "...Z". Страницы писем и слияние списка
-- сравнивают дату как строку, поэтому при разных смещениях порядок расходился:
-- часть писем не попадала ни в одну страницу, часть возвращалась повторно.
UPDATE messages
   SET date = strftime('%Y-%m-%dT%H:%M:%S+00:00', date)
 WHERE date IS NOT NULL
   AND date NOT LIKE '%+00:00'
   AND strftime('%Y-%m-%dT%H:%M:%S+00:00', date) IS NOT NULL;
