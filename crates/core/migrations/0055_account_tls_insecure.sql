-- Выключатель проверки сертификата на отдельный ящик (issue #118). Почтовый
-- сервер организации может отдавать самоподписанный сертификат, и без этого
-- признака такой ящик подключить нельзя вовсе. Признак принадлежит ящику:
-- соседние ящики продолжают проверяться как обычно. Значение по умолчанию 0 -
-- у существующих ящиков проверка остаётся включённой.
ALTER TABLE accounts ADD COLUMN tls_insecure INTEGER NOT NULL DEFAULT 0;
