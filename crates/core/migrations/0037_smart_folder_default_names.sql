-- Имя встроенной умной папки хранится только тогда, когда его задал
-- пользователь. Пустое имя означает "подпись по умолчанию" - интерфейс берёт её
-- из локализации и меняет вместе с языком. Раньше в базе лежали имена из первой
-- миграции, интерфейс сравнивал их с собственным списком и из-за этого не
-- показывал переименованные папки.

-- Перечислены только те имена, которые программа записывала сама: посев
-- миграции 0006 и значения, возвращавшиеся в базу интерфейсом. Английские
-- подписи и короткие формы вроде "Непрочитанные" в базу автоматически не
-- попадали никогда, поэтому их наличие означает переименование пользователем -
-- такое имя стирать нельзя.
UPDATE smart_folders SET name = '' WHERE is_builtin = 1 AND (
       (stable_id = 'all-inbox'         AND name = 'Все входящие')
    OR (stable_id = 'all-important'     AND name = 'Все важные')
    OR (stable_id = 'all-sent'          AND name = 'Все отправленные')
    OR (stable_id = 'all-drafts'        AND name = 'Все черновики')
    OR (stable_id = 'last-24-hours'     AND name IN ('Сегодня', 'Сегодня (за 24 часа)'))
    OR (stable_id = 'all-unread'        AND name = 'Непрочитанные (все)')
    OR (stable_id = 'with-attachments'  AND name = 'С вложениями')
    OR (stable_id = 'awaiting-my-reply' AND name = 'Ждут ответа')
);
