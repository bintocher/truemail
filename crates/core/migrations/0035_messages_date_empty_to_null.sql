-- Пустая строка вместо даты ломала бы порядок страниц: сортировка ставит '' выше
-- NULL, а фильтр курсора считает их одинаковыми, и письма с пустой датой могли
-- бы пропасть между страницами. Своя запись такого не создаёт, но данные могли
-- прийти из импорта или старых версий.
UPDATE messages SET date = NULL WHERE date = '';
