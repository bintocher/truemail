-- Пять цветов палитры затемнены, чтобы подпись поверх них проходила порог
-- контраста AA (4.5:1): ни белый, ни тёмный текст на прежних оттенках его не
-- достигали. Цвет аккаунта и метки хранится в базе, поэтому у тех, кто выбрал
-- оттенок раньше, там осталось старое значение - подтягиваем его к новому.
-- Заменяем только точные совпадения с прежней палитрой: цвет, заданный
-- пользователем вручную помимо неё, остаётся как есть.

UPDATE accounts SET color = CASE color
    WHEN '#d64545' THEN '#d24444'
    WHEN '#b355c0' THEN '#ac52b8'
    WHEN '#c65a8e' THEN '#b85484'
    WHEN '#b8622a' THEN '#b46029'
    WHEN '#5d8a2f' THEN '#57822c'
    ELSE color
END
WHERE color IN ('#d64545', '#b355c0', '#c65a8e', '#b8622a', '#5d8a2f');

